#!/bin/bash
# Read-only validation is separate from copying the validated certificate chain.
source "$(dirname "${BASH_SOURCE[0]}")/ipv4.sh"
certificates_validate() {
    local cert="$1" key="$2" domain="$3" cert_public key_public
    # Trust this leaf only for the local identity/date/purpose check; this is
    # not a claim that its issuer is trusted by remote clients.
    local -a verify_args=(-trusted "$cert" -partial_chain -purpose sslserver)
    [[ -f "$cert" && -f "$key" ]] || { echo '错误: 找不到服务器证书或私钥' >&2; return 1; }
    openssl x509 -in "$cert" -noout -checkend 0 >/dev/null 2>&1 || {
        echo '错误: 服务器证书无效或已过期' >&2; return 1;
    }
    if ipv4_number "$domain" >/dev/null 2>&1; then
        verify_args+=(-verify_ip "$domain")
    else
        verify_args+=(-verify_hostname "$domain")
    fi
    openssl verify "${verify_args[@]}" "$cert" >/dev/null 2>&1 || {
        echo '错误: 服务器证书的域名/IP、有效期或服务端用途不匹配' >&2; return 1;
    }
    cert_public="$(set -o pipefail; openssl x509 -in "$cert" -pubkey -noout | openssl pkey -pubin -outform DER | sha256sum)" || return 1
    key_public="$(set -o pipefail; openssl pkey -in "$key" -passin pass: -pubout -outform DER 2>/dev/null | sha256sum)" || {
        echo '错误: 私钥无法读取，不支持需要交互输入密码的私钥' >&2; return 1;
    }
    [[ "$cert_public" == "$key_public" ]] || { echo '错误: 服务器证书和私钥不匹配' >&2; return 1; }
}

certificates_prepare() {
    local cert="$1" key="$2" root="$3" temporary chain
    mkdir -p "$root/x509" "$root/x509ca" "$root/private" || return 1
    temporary="$(mktemp -d "$root/.certificates.XXXXXX")" || return 1
    if ! awk -v directory="$temporary" '
        /-----BEGIN CERTIFICATE-----/ { n++; file = (n == 1 ? directory "/cert.pem" : sprintf("%s/chain-%02d.pem", directory, n - 1)) }
        { if (n > 0) print > file }
    ' "$cert" || [[ ! -s "$temporary/cert.pem" ]]; then
        rm -rf -- "$temporary"
        echo '错误: 证书链拆分失败' >&2
        return 1
    fi
    # Only remove files generated by this module, not arbitrary user CA files.
    for chain in "$root"/x509ca/chain-[0-9]*.pem; do
        [[ ! -f "$chain" ]] || rm -f -- "$chain" || { rm -rf -- "$temporary"; return 1; }
    done
    if ! install -m 600 "$key" "$root/private/privkey.pem" || \
       ! install -m 644 "$temporary/cert.pem" "$root/x509/cert.pem"; then
        rm -rf -- "$temporary"
        return 1
    fi
    for chain in "$temporary"/chain-*.pem; do
        if [[ -f "$chain" ]]; then
            install -m 644 "$chain" "$root/x509ca/" || { rm -rf -- "$temporary"; return 1; }
        fi
    done
    rm -rf -- "$temporary"
}
